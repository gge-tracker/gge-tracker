import * as fs from 'node:fs';
import * as path from 'node:path';

import { lootStreams } from './loot-streams';
import { Random } from './random';
import { GeneratedPlayer, World, buildWorld, playerObject } from './world';

const OUT = path.join(__dirname, '..', 'fixtures');
const ZONE = 'EmpireEx_3';
const GENERATED_AT = '2026-11-01T12:00:00.000Z';

function meta(name: string, describes: string, rowCount: number, complete: boolean): Record<string, unknown> {
  return {
    name,
    describes,
    capturedAt: GENERATED_AT,
    capturedFrom: 'generated by tests/fixture-generator',
    rowCount,
    complete,
    anonymised: true,
  };
}

function write(name: string, content: Record<string, unknown>): void {
  fs.writeFileSync(path.join(OUT, `${name}.json`), JSON.stringify(content) + '\n');
}

interface RankingSpec {
  name: string;
  describes: string;
  lt: number;
  lid: number;
  pageSize: number;
  complete: boolean;
  entries: { playerId: number; score: number }[];
}

function writeRanking(world: World, spec: RankingSpec): void {
  const rows = spec.entries.map((entry, index) => [index + 1, entry.score, playerObject(world, entry.playerId)]);
  write(spec.name, {
    meta: meta(spec.name, spec.describes, rows.length, spec.complete),
    lt: spec.lt,
    lid: spec.lid,
    pageSize: spec.pageSize,
    totalRanked: rows.length,
    fr: 1,
    igh: 0,
    rows,
  });
}

function descending(random: Random, count: number, high: number, low: number): number[] {
  return Array.from({ length: count }, () => Math.round(random.between(low, high))).sort((a, b) => b - a);
}

function rankBy(
  world: World,
  filter: (id: number) => boolean,
  count: number,
  score: (id: number) => number,
): { playerId: number; score: number }[] {
  return world.players
    .filter((player) => filter(player.id))
    .map((player) => ({ playerId: player.id, score: score(player.id) }))
    .sort((a, b) => b.score - a.score)
    .slice(0, count);
}

function main(): void {
  const random = new Random(20_261_101);
  const world = buildWorld(random);
  const player = (id: number): GeneratedPlayer => world.byId.get(id)!;

  const mightBands: [number, (id: number) => boolean, number][] = [
    [1, (id): boolean => player(id).level < 20, 60],
    [2, (id): boolean => player(id).level >= 20 && player(id).level < 30, 40],
    [3, (id): boolean => player(id).level >= 30 && player(id).level < 40, 40],
    [4, (id): boolean => player(id).level >= 40 && player(id).level < 50, 40],
    [5, (id): boolean => player(id).level >= 50 && player(id).level < 70, 40],
    [6, (id): boolean => player(id).level === 70 && player(id).legendaryLevel === 950, 40],
  ];
  for (const [lid, filter, count] of mightBands) {
    writeRanking(world, {
      name: `hgh-might-lt6-lid${lid}`,
      describes: `Might points, category ${lid}, first pages`,
      lt: 6,
      lid,
      pageSize: 10,
      complete: false,
      entries: rankBy(world, filter, count, (id) => player(id).might),
    });
  }

  const legendary =
    (low: number, high: number) =>
    (id: number): boolean =>
      player(id).level === 70 && player(id).legendaryLevel >= low && player(id).legendaryLevel <= high;
  const nomadBands: [number, (id: number) => boolean, number, number, [number, number], boolean][] = [
    [1, (id): boolean => player(id).level < 70 || player(id).legendaryLevel < 10, 172, 0.9, [35, 61_000], true],
    [2, legendary(10, 300), 64, 1, [29_000, 730_000], false],
    [3, legendary(301, 649), 40, 1, [120_000, 2_270_000], false],
    [4, legendary(650, 949), 40, 1, [128_000, 4_740_000], false],
    [5, legendary(950, 950), 40, 1, [5_750_000, 108_000_000], false],
  ];
  for (const [lid, filter, count, share, [low, high], complete] of nomadBands) {
    const entrants = world.players.filter((candidate) => filter(candidate.id) && random.chance(share)).slice(0, count);
    const scores = descending(random, entrants.length, high, low);
    writeRanking(world, {
      name: `hgh-nomads-lt46-lid${lid}`,
      describes:
        lid === 1
          ? 'Nomad invasion, category 1, the whole live ranking'
          : `Nomad invasion, category ${lid}, first pages`,
      lt: 46,
      lid,
      pageSize: 8,
      complete,
      entries: random.shuffle(entrants).map((entrant, index) => ({ playerId: entrant.id, score: scores[index] })),
    });
  }

  const looters = world.players.filter((candidate) => candidate.topLooter);
  const lootScores = descending(random, 60, 2_087_000_000, 1_263_000_000);
  writeRanking(world, {
    name: 'hgh-loot-lt2-head',
    describes: 'Weekly loot ranking, top of the ladder',
    lt: 2,
    lid: 1,
    pageSize: 10,
    complete: false,
    entries: looters.slice(0, 60).map((looter, index) => ({ playerId: looter.id, score: lootScores[index] })),
  });

  // A counter past 2^31 reads negative, so the bottom of the ladder holds the biggest looters of all
  const tail = world.players.filter((candidate) => candidate.tailLooter).slice(0, 40);
  const negatives = descending(random, 13, -1_808_000_000, -2_140_800_000);
  writeRanking(world, {
    name: 'hgh-loot-lt2-tail',
    describes: 'Weekly loot ranking, bottom of the ladder where scores overflow into negatives',
    lt: 2,
    lid: 1,
    pageSize: 10,
    complete: false,
    entries: tail.map((looter, index) => ({ playerId: looter.id, score: index < 27 ? 0 : negatives[index - 27] })),
  });

  const wheelEntrants = world.players
    .filter((candidate) => candidate.level === 70 && candidate.legendaryLevel >= 115 && random.chance(0.06))
    .slice(0, 26);
  const wheelScores = descending(random, wheelEntrants.length, 390, 1);
  wheelScores[wheelScores.length - 1] = 1;
  writeRanking(world, {
    name: 'hgh-wheel-lt72',
    describes: 'Wheel of Unimaginable Affluence, the whole live ranking',
    lt: 72,
    lid: 1,
    pageSize: 8,
    complete: true,
    entries: wheelEntrants.map((entrant, index) => ({ playerId: entrant.id, score: wheelScores[index] })),
  });

  writeEmptyRankings();
  writeAlliances(
    world,
    looters.slice(0, 10).map((looter) => looter.allianceId!),
  );
  writeAquamarine(
    random,
    world,
    looters.slice(0, 10).map((looter) => looter.id),
  );
  const loot = lootStreams();
  write('loot-streams', {
    meta: meta(
      'loot-streams',
      'player_loot_history streams around a 2^32 wrap, an early reset or a decrease, one per case, without player ids',
      0,
      false,
    ),
    streams: loot.streams,
  });
  for (const [name, expected] of Object.entries(loot.expectations)) {
    console.log(
      `  ${name}: ${expected.map((each) => `${new Date(each.at).toISOString()} ${each.kind} ${each.point}`).join(' | ')}`,
    );
  }
  console.log(`  ${fs.readdirSync(OUT).filter((file) => file.endsWith('.json')).length} fixtures written to ${OUT}`);
}

